"""
Module 14 — Email & Notification Service
==========================================
Handles email notifications via Gmail SMTP (SSL 465).
Supports:
  - Report Ready Notification (Student & Assigned Guide)
  - Review Submitted Alert (Student)
  - Appeal Decision Alert (Student)
  - Viva Session Completed Alert (Guide & Student)
  - Flagged Proposal Alert (Guide & HOD for High Similarity / Low Quality)
"""

import logging
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Optional, List

from app.config import settings

log = logging.getLogger(__name__)


def send_email(to: str, subject: str, body_html: str, body_text: Optional[str] = None) -> bool:
    """
    Sends an email using Gmail SMTP_SSL (port 465) with plain text + HTML formatting.
    Degrades gracefully — logs warning if credentials missing or network fails.
    """
    if not settings.SMTP_USER or not settings.SMTP_PASSWORD:
        log.warning("SMTP not configured. Skipping email to %s (Subject: %r)", to, subject)
        return False

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = f"{settings.SMTP_FROM_NAME} <{settings.SMTP_USER}>"
    msg["To"] = to

    # Attach plain text fallback
    plain_content = body_text or "Please view this email in an HTML-compatible client."
    msg.attach(MIMEText(plain_content, "plain", "utf-8"))

    # Attach HTML body
    msg.attach(MIMEText(body_html, "html", "utf-8"))

    try:
        with smtplib.SMTP_SSL(settings.SMTP_SERVER, settings.SMTP_PORT, timeout=12.0) as server:
            server.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
            server.send_message(msg)
        log.info("Email successfully sent to %s (Subject: %r)", to, subject)
        return True
    except Exception as exc:
        log.error("Failed to send email to %s: %s", to, exc)
        return False


