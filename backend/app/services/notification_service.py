# ── Notification Helper Functions ─────────────────────────────────────────────

def notify_report_ready(student_email: str, student_name: str, project_title: str, overall_score: float, grade: str, project_id: str):
    """Notification sent to student when AI evaluation report is generated."""
    subject = f"Evaluation Report Ready: {project_title}"
    body_html = _email_container(
        title="Evaluation Complete",
        content_html=f"""
            <p>Dear <strong>{student_name}</strong>,</p>
            <p>Your capstone proposal evaluation report for <strong>"{project_title}"</strong> has been generated by the AcadEval+ AI Engine.</p>
            <div class="metric-box">
                <p style="margin:0;"><strong>Overall Score:</strong> {overall_score} / 100</p>
                <p style="margin:5px 0 0 0;"><strong>Grade:</strong> {grade}</p>
            </div>
            <p>You can now log in to view your complete breakdown, including your Knowledge Graph, Writing Quality, and Novelty Signals.</p>
            <a href="{settings.FRONTEND_ORIGIN}/student/reports/{project_id}" class="btn">View Full Evaluation Report</a>
        """
    )
    send_email(student_email, subject, body_html)


