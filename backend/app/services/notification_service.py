def notify_proposal_flagged(hod_email: str, hod_name: str, project_title: str, student_name: str, flags: List[str], project_id: str):
    """Alert sent to HOD / Guide when a proposal triggers critical quality/plagiarism flags."""
    flags_list_html = "".join([f"<li>{f}</li>" for f in flags])
    subject = f"⚠️ Flagged Proposal Alert: {project_title}"
    body_html = _email_container(
        title="High Severity Alert",
        content_html=f"""
            <p>Dear <strong>{hod_name}</strong>,</p>
            <p>The proposal <strong>"{project_title}"</strong> submitted by <strong>{student_name}</strong> has triggered automated quality or similarity alerts:</p>
            <div class="metric-box" style="border-left-color: #e11d48; background: #fff1f2;">
                <ul style="margin:0; padding-left:20px; color:#be123c;">
                    {flags_list_html}
                </ul>
            </div>
            <p>Please inspect the explainable report to decide on further action.</p>
            <a href="{settings.FRONTEND_ORIGIN}/faculty/projects/{project_id}" class="btn" style="background:#e11d48;">Inspect Flagged Project</a>
        """
    )
    send_email(hod_email, subject, body_html)
